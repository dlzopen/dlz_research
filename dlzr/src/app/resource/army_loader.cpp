const uint8_t* ArmyLoader::palette() { return ARMY_PALETTE; }

bool ArmyLoader::load(const std::string& path) {
    std::ifstream file(path, std::ios::binary);
    if (!file) {
        std::fprintf(stderr, "ArmyLoader: cannot open %s\n", path.c_str());
        return false;
    }

    file.seekg(0, std::ios::end);
    size_t file_size = file.tellg();
    file.seekg(0, std::ios::beg);

    size_t expected = static_cast<size_t>(ENTRY_SIZE) * ENTRY_COUNT;
    if (file_size < expected) {
        std::fprintf(stderr, "ArmyLoader: file too small (%zu < %zu)\n",
                     file_size, expected);
        return false;
    }

    raw_data_.resize(expected);
    file.read(reinterpret_cast<char*>(raw_data_.data()), expected);

    build_rgba_cache();
    return true;
}

void ArmyLoader::build_rgba_cache() {
    const uint8_t* pal = ARMY_PALETTE;
    // Cache all 19 frames for each of 91 entries
    rgba_cache_.resize(ENTRY_COUNT * FRAME_COUNT);

    for (int32_t e = 0; e < ENTRY_COUNT; ++e) {
        for (int32_t f = 0; f < FRAME_COUNT; ++f) {
            int32_t cache_idx = e * FRAME_COUNT + f;
            rgba_cache_[cache_idx].resize(ICON_SIZE * 4);
            const uint8_t* src = raw_data_.data() + e * ENTRY_SIZE + f * ICON_SIZE;
            uint8_t* dst = rgba_cache_[cache_idx].data();

            for (int32_t p = 0; p < ICON_SIZE; ++p) {
                uint8_t idx = src[p];
                dst[p * 4 + 0] = pal[idx * 4 + 0];
                dst[p * 4 + 1] = pal[idx * 4 + 1];
                dst[p * 4 + 2] = pal[idx * 4 + 2];
                dst[p * 4 + 3] = (idx == 0) ? 0 : pal[idx * 4 + 3];
            }
        }
    }
}

const uint8_t* ArmyLoader::get_icon_rgba(int32_t entry_index) const {
    // Return first frame (idle frame 0) for UI icons
    return get_frame_rgba(entry_index, 0);
}

const uint8_t* ArmyLoader::get_frame_rgba(int32_t entry_index, int32_t frame_index) const {
    if (entry_index < 0 || entry_index >= ENTRY_COUNT) return nullptr;
    if (frame_index < 0 || frame_index >= FRAME_COUNT) return nullptr;
    int32_t cache_idx = entry_index * FRAME_COUNT + frame_index;
    if (cache_idx >= static_cast<int32_t>(rgba_cache_.size())) return nullptr;
    return rgba_cache_[cache_idx].data();
}

const uint8_t* ArmyLoader::get_action_frame_rgba(int32_t entry_index,
                                                   int32_t action_type,
                                                   Direction direction,
                                                   int32_t anim_counter) const {
    // Frame selection formula from RE FUN_004170aa:
    //   action_type 0 (idle):   frame = anim_counter % 2
    //   action_type 1 (move):   frame = (dir % 4) * 2 + 2 + anim_counter % 2
    //   action_type 2 (attack): frame = (dir % 4) * 2 + 10 + anim_counter % 2
    //   action_type 3 (hit):    frame = 18
    int32_t frame = 0;
    int32_t dir = static_cast<int32_t>(direction) % 4;
    int32_t alt = anim_counter % 2;

    switch (action_type) {
    case 0:  // Idle
        frame = alt;  // 0-1
        break;
    case 1:  // Move
        frame = dir * 2 + 2 + alt;  // 2-9
        break;
    case 2:  // Attack
        frame = dir * 2 + 10 + alt;  // 10-17
        break;
    case 3:  // Hit/Death
        frame = FRAME_HIT;  // 18
        break;
    default:
        frame = 0;
        break;
    }

    return get_frame_rgba(entry_index, frame);
}

