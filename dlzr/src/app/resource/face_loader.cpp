bool FaceLoader::load(const std::string& path) {
    std::ifstream file(path, std::ios::binary);
    if (!file) {
        std::fprintf(stderr, "FaceLoader: cannot open %s\n", path.c_str());
        return false;
    }

    file.seekg(0, std::ios::end);
    size_t file_size = file.tellg();
    file.seekg(0, std::ios::beg);

    // Face portrait data starts at offset 0xC92C0 in FACE.DAT
    // (RE: DAT_004761f8 + (index + 0x67) * 8000)
    static const size_t FACE_DATA_OFFSET = 0xC92C0;
    size_t expected = FACE_DATA_OFFSET + static_cast<size_t>(FACE_SIZE) * FACE_COUNT;
    if (file_size < expected) {
        std::fprintf(stderr, "FaceLoader: file too small (%zu < %zu)\n",
                     file_size, expected);
        return false;
    }

    // Skip to face data offset
    file.seekg(FACE_DATA_OFFSET, std::ios::beg);

    raw_data_.resize(static_cast<size_t>(FACE_SIZE) * FACE_COUNT);
    file.read(reinterpret_cast<char*>(raw_data_.data()),
              static_cast<size_t>(FACE_SIZE) * FACE_COUNT);

    build_rgba_cache();
    return true;
}

void FaceLoader::build_rgba_cache() {
    const uint8_t* pal = FACE_PALETTE;
    rgba_cache_.resize(FACE_COUNT);

    for (int32_t f = 0; f < FACE_COUNT; ++f) {
        rgba_cache_[f].resize(FACE_SIZE * 4);
        const uint8_t* src = raw_data_.data() + f * FACE_SIZE;
        uint8_t* dst = rgba_cache_[f].data();

        for (int32_t p = 0; p < FACE_SIZE; ++p) {
            uint8_t idx = src[p];
            dst[p * 4 + 0] = pal[idx * 4 + 0];
            dst[p * 4 + 1] = pal[idx * 4 + 1];
            dst[p * 4 + 2] = pal[idx * 4 + 2];
            dst[p * 4 + 3] = pal[idx * 4 + 3];
        }
    }
}

const uint8_t* FaceLoader::get_face_rgba(int32_t index) const {
    if (index < 0 || index >= FACE_COUNT) return nullptr;
    if (index >= static_cast<int32_t>(rgba_cache_.size())) return nullptr;
    return rgba_cache_[index].data();
}

